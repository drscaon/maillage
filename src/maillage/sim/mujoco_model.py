"""MuJoCo model (MJCF) of cloth pieces, built from the OpenUSD file only.

Each piece is a MuJoCo flex: a triangle shell (``flexcomp type="direct"``,
``dim="2"``) with the piece's vertices and triangles (quads split in two),
its total mass spread over the vertices, and shell elasticity
(``elastic2d="both"``: membrane and bending) from the engine-neutral
stiffness in the file: a Young's modulus and a thickness that give exactly
the fabric's tensile stiffness and bending rigidity (see fabrics.shell).
Contacts use the fabric's friction.

Solver settings that keep a stiff membrane on a light fabric stable, found
with the drape test (MuJoCo 3.17): the ``discrete`` integrator (flex
elasticity is integrated implicitly only there), a 0.5 ms time step, the CG
solver with a tight tolerance, a small elastic damping.

MuJoCo has no air drag on flex vertices that the XML can express: the drape
test applies it as a force, ``AIR_DAMPING`` N·s/m³ times each vertex's share
of the cloth area, the order of real air drag on cloth at draping speeds.
Without it a draped piece swings for a long time.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from .usd_reader import Piece, find_usd, read_pieces

TIMESTEP = 5e-4  # s
ELASTIC_DAMPING = 0.002  # s, Rayleigh damping of the shell elasticity
AIR_DAMPING = 1.0  # N·s/m³, applied by the test loop
RADIUS = 0.002  # m, collision radius of the cloth (Blender's test uses 4 mm between surfaces)
CONDITION = 3.0  # largest K dt² / vertex mass: above it, MuJoCo's flex solve is ill-conditioned


def timestep(pieces) -> float:
    """TIMESTEP, or smaller for a stiff membrane on light vertices (a small linen napkin)."""
    dt = TIMESTEP
    for p in pieces:
        m_v = p.mass / len(p.points)
        dt = min(dt, float(np.sqrt(CONDITION * m_v / float(p.attrs["tensileStiffness"]))))
    return dt


def _f(v) -> str:
    return " ".join(f"{x:.7g}" for x in np.ravel(v))


def shell(piece: Piece) -> tuple[float, float, float]:
    """(Young's modulus, thickness, Poisson's ratio) from the file's engine-neutral stiffness."""
    a = piece.attrs
    K, B, nu = float(a["tensileStiffness"]), float(a["bendingRigidity"]), float(a["poissonsRatio"])
    t = float(np.sqrt(12 * (1 - nu * nu) * B / K))
    return K / t, t, nu


def flex_xml(piece: Piece, points_world: np.ndarray, pinned=(), timestep: float = TIMESTEP) -> str:
    E, t, nu = shell(piece)
    mu = float(piece.attrs.get("friction", 0.5))
    pin = f'<pin id="{" ".join(str(int(i)) for i in pinned)}"/>' if len(pinned) else ""
    return (
        f'<flexcomp name="{piece.name}" type="direct" dim="2" point="{_f(points_world)}" '
        f'element="{_f(piece.triangles)}" mass="{piece.mass:.7g}" radius="{RADIUS}" rgba="0.8 0.75 0.65 1">'
        f'<elasticity young="{E:.7g}" poisson="{nu:.4g}" thickness="{t:.7g}" damping="{ELASTIC_DAMPING}" '
        f'elastic2d="both"/>'
        f'<contact condim="3" friction="{mu:.4g}" solref="{2 * timestep:.4g} 1" selfcollide="none"/>'
        f'<edge equality="false"/>{pin}</flexcomp>'
    )


def model_xml(flexes: list[str], world: str = "", timestep: float = TIMESTEP, comment: str = "") -> str:
    return (
        f'<mujoco model="maillage">{f"<!-- {comment} -->" if comment else ""}'
        f'<option timestep="{timestep}" integrator="discrete" solver="CG" tolerance="1e-10" '
        'iterations="100"/>'
        f'<worldbody><geom name="floor" type="plane" size="0 0 0.05" friction="0.5"/>{world}'
        f"{''.join(flexes)}</worldbody></mujoco>"
    )


def export(usd, out_xml=None) -> Path:
    """MJCF of the scene as in the file: every piece flat on the floor at its place."""
    usd = find_usd(usd)
    pieces = read_pieces(usd)
    dt = timestep(pieces)
    flexes = []
    for p in pieces:
        pts = p.points + p.position
        pts[:, 2] = pts[:, 2] - pts[:, 2].min() + RADIUS + 1e-3
        flexes.append(flex_xml(p, pts, timestep=dt))
    out = Path(out_xml) if out_xml else usd.with_suffix(".xml")
    note = (
        f"Generated by maillage from {usd.name}. Flex cloths with shell elasticity from the file's "
        "tensile stiffness and bending rigidity. Not expressible here: air drag on the cloth "
        f"(maillage's drape test applies {AIR_DAMPING} N s/m3 per unit area) and pinned vertices "
        "(the 'pin' primvar of the USD file)."
    )
    out.write_text(model_xml(flexes, timestep=dt, comment=note) + "\n", encoding="utf-8")
    return out
